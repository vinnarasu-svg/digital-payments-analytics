//Find customers who used more than one payment method.
SELECT 
    c.customer_id,
    c.customer_name,count(distinct t.payment_method) as payment_method_used
FROM transaction t
JOIN customer c 
    ON t.customer_id = c.customer_id
WHERE t.payment_status = 'Success'
GROUP BY c.customer_id, c.customer_name
HAVING COUNT(DISTINCT t.payment_method) > 1;

//Find the Top 5 customers with the highest number of successful transactions.
