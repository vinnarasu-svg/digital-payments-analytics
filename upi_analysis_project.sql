//Find the Top 2 merchants in each category based on revenue.
WITH merchant_revenue AS (
    SELECT 
        m.merchant_name,
        m.category,
        SUM(CASE 
                WHEN t.payment_status = 'Success' 
                THEN t.amount 
                ELSE 0 
            END) AS total_revenue
    FROM transaction t
    JOIN merchant m 
        ON m.merchant_id = t.merchant_id
    GROUP BY m.merchant_name, m.category
)

SELECT 
    merchant_name,
    category,
    total_revenue,
    ROW_NUMBER() OVER (
        PARTITION BY category 
        ORDER BY total_revenue DESC
    ) AS rn
FROM merchant_revenue
QUALIFY rn <= 2;

